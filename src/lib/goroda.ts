// остальные открываются страницей «рейтинг собирается» (noindex, пока нет данных – не дорвей) с заявкой компании.
export interface Gorod {
  slug: string;
  name: string;
  of: string; // «Новосибирска»
  in: string; // «в Новосибирске»
  ready: boolean;
}

const g = (slug: string, name: string, of: string, inn: string, ready = false): Gorod => ({ slug, name, of, in: inn, ready });

