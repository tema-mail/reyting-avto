export const gorod = (slug: string): Gorod => GORODA.find((x) => x.slug === slug)!;
/** Города с собранным рейтингом. */
export const READY: Gorod[] = GORODA.filter((x) => x.ready);
/** Город по адресу страницы: /<город>/… */
export const gorodOf = (path: string): Gorod | undefined => GORODA.find((x) => path.split('/').includes(x.slug));
